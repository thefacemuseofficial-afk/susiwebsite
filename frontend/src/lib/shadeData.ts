/**
 * Validates a built retailer link.
 * - URL must parse and use https
 * - Must use the expected query key for that retailer (if any)
 * - The expected key's value must be non-empty AND match the encoded query
 * - For path-based search (queryKey === null), the path must contain the encoded query
 * - Rejects empty/whitespace queries and any URL with empty query parameters
 */
export function isValidRetailerLink(
  link: { name: string; url: string },
  query: string,
  siteKey?: string,
): boolean {
  if (!query || !query.trim()) return false;
  if (!link.url || typeof link.url !== "string") return false;

  let parsed: URL;
  try {
    parsed = new URL(link.url);
  } catch {
    return false;
  }
  if (parsed.protocol !== "https:") return false;

  const encodedQuery = encodeURIComponent(query.trim());
  const decodedExpected = query.trim();

  // Reject any URL that contains a query parameter with an empty value
  // (e.g. ?q=&foo=bar) — these break retailer search pages.
  for (const [, value] of parsed.searchParams.entries()) {
    if (value === "" || value.trim() === "") return false;
  }

  // If we know the retailer's expected query key, enforce it
  const expectedKey = siteKey ? retailerQueryKeys[siteKey] : undefined;

  if (expectedKey === null) {
    // Path-based search — the encoded query must appear in the pathname
    if (!parsed.pathname.includes(encodedQuery) && !parsed.pathname.includes(decodedExpected)) {
      return false;
    }
    return true;
  }

  if (expectedKey) {
    const value = parsed.searchParams.get(expectedKey);
    if (value === null) return false;
    if (value.trim() === "") return false;
    // Value (already URL-decoded by searchParams) should match the raw query
    if (value !== decodedExpected) return false;
    return true;
  }

  // Unknown retailer — fall back to: must have a non-empty search string
  // OR the encoded query in the path.
  const hasQuery = parsed.search.length > 1 || parsed.pathname.includes(encodedQuery);
  return hasQuery;
}

