export function getShadesForCategoryWithOverrides(
  category: string,
  fitzpatrick: FitzpatrickType,
  overrides: ShadeCatalogueOverridesShape | null | undefined,
): ShadeRecommendation[] {
  const base = getShadesForCategory(category, fitzpatrick);
  const extra =
    overrides?.byFitzpatrick?.[category]?.[String(fitzpatrick) as "1" | "2" | "3" | "4" | "5" | "6"] ?? [];
  if (!extra.length) return base;
  // Dedupe by brand+product+shade — override entries take precedence.
  const key = (r: ShadeRecommendation) => `${r.brand}|${r.product}|${r.shade}`;
  // If overrides expand a brand's product range for this category, drop all
  // base rows for that same brand+product so the override is authoritative.
  const overriddenBrandProducts = new Set(extra.map((r) => `${r.brand}|${r.product}`));
  const overrideKeys = new Set(extra.map(key));
  const filteredBase = base.filter(
    (r) => !overrideKeys.has(key(r)) && !overriddenBrandProducts.has(`${r.brand}|${r.product}`),
  );
  return [...filteredBase, ...extra];
}

export function getEyeshadowByEyeColourWithOverrides(
  eyeColour: EyeColour,
  overrides: ShadeCatalogueOverridesShape | null | undefined,
): ShadeRecommendation[] {
  const base = getEyeshadowByEyeColour(eyeColour);
  const extra = overrides?.eyeshadowByEyeColour?.[eyeColour] ?? [];
  return extra.length ? [...base, ...extra] : base;
}



