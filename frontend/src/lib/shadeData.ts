// ── Public API ─────────────────────────────────────────────────────

export function getShadesForCategory(
  category: string,
  fitzpatrick: FitzpatrickType = 2
): ShadeRecommendation[] {
  const map: Record<string, Record<FitzpatrickType, ShadeRecommendation[]>> = {
    foundation: foundationByFitz,
    concealer: concealerByFitz,
    contour: contourByFitz,
    bronzer: bronzerByFitz,
    highlighter: highlighterByFitz,
    lipstick: lipstickByFitz,
  };
  const byFitz = map[category];
  if (byFitz) {
    const base = byFitz[fitzpatrick] ?? byFitz[2];
    return [
      ...base,
      ...(revolutionByFitz[category]?.[fitzpatrick] ?? []),
      ...(expandedByFitz[category]?.[fitzpatrick] ?? []),
    ];
  }
  // eyeshadow defaults to brown eyes
  if (category === "eyeshadow") return getEyeshadowByEyeColour("brown");
  return [];
}

export function getEyeshadowByEyeColour(eyeColour: EyeColour): ShadeRecommendation[] {
  const base = eyeshadowByEyeColour[eyeColour] ?? eyeshadowByEyeColour.brown;
  return [
    ...base,
    ...(revolutionEyeshadowByEyeColour[eyeColour] ?? []),
    ...(expandedEyeshadowByEyeColour[eyeColour] ?? []),
    ...(complementaryEyeshadowExtras[eyeColour] ?? []),
    ...(vibrantEyeshadowExtras[eyeColour] ?? []),
  ];
}

