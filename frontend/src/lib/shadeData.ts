// Get retailer keys available in a region (from any brand's mapping).
export function getRetailersForRegion(region: Region): string[] {
  const set = new Set<string>();
  for (const map of Object.values(brandRetailers)) {
    for (const key of map[region] ?? []) set.add(key);
  }
  return Array.from(set).sort();
}

// Get brand names sold at a given retailer in a region.
export function getBrandsForRetailer(retailerKey: string, region: Region): string[] {
  const brandsList: string[] = [];
  for (const [brand, map] of Object.entries(brandRetailers)) {
    if ((map[region] ?? []).includes(retailerKey)) brandsList.push(brand);
  }
  return brandsList;
}

// Per-product overrides — only when a specific product differs from the
// brand-wide retailer footprint. Otherwise the brand-level map (which is
// region-accurate) is used.
const productRetailerOverrides: Record<string, Partial<Record<Region, string[]>>> = {};

export function getRetailerLinks(brandName: string, productName: string, productQuery: string, region: Region = "OTHER"): RetailerLink[] {
  // Runtime guard: never render a retailer link for an empty query.
  if (!productQuery || !productQuery.trim()) {
    if (typeof console !== "undefined") {
      console.warn(`[getRetailerLinks] Empty productQuery for ${brandName} / ${productName}`);
    }
    return [];
  }
  const productMap = productRetailerOverrides[`${brandName}::${productName}`];
  const brandMap = brandRetailers[brandName];
  const map = productMap ?? brandMap;
  if (!map) return [];
  const keys = map[region] ?? map["OTHER"] ?? [];
  return keys
    .map((key) => {
      const site = retailerSites[key];
      if (!site) return null;
      const link = { name: site.name, url: site.searchUrl(productQuery) };
      if (!isValidRetailerLink(link, productQuery, key)) {
        if (typeof console !== "undefined") {
          console.warn(`[getRetailerLinks] Invalid link for ${key}:`, link.url);
        }
        return null;
      }
      return link;
    })
    .filter((r): r is RetailerLink => r !== null);
}

